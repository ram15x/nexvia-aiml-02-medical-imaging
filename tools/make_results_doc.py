"""Write docs/results.md from the pipeline outputs. No figure is typed by hand."""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

RESULTS = Path("results/nih_sample")
OUTPUT = Path("docs/results.md")


def fmt_ci(value) -> str:
    if value is None:
        return "not estimable"
    low, high = value
    return f"{low:.3f}–{high:.3f}"


def build() -> str:
    data = json.loads((RESULTS / "per_label_intervals.json").read_text(encoding="utf-8"))
    macro = data["macro"]
    lines = [
        "# Classifier results: NIH ChestX-ray14 sample (generated)",
        "",
        "Generated by `tools/make_results_doc.py` from `results/nih_sample/`. Do not edit by hand.",
        "",
        "Model: the served DenseNet-121 checkpoint `artifacts/best_densenet121.pt` (8k+10k weight average).",
        "Data: 999 images from 549 patients, from the NIH official test split (`data/nih_test_sample_1000`).",
        "This is a sample, not the full official test split. Labels are report-mined and noisy.",
        "Whether this sample was used in earlier model selection cannot be verified from this repository.",
        "These figures are evaluation results on one sample, not an independent clinical test.",
        "",
        "## Overall",
        "",
        "| Metric | Value |",
        "|---|---:|",
        f"| Macro AUROC (labels with both classes) | {macro['macro_auroc_defined_labels']:.4f} |",
        f"| Macro average precision (same labels) | {macro['macro_auprc_defined_labels']:.4f} |",
        f"| Micro precision at 0.5 | {macro['micro_precision_at_0_5']:.4f} |",
        f"| Micro recall at 0.5 | {macro['micro_recall_at_0_5']:.4f} |",
        f"| Micro F1 at 0.5 | {macro['micro_f1_at_0_5']:.4f} |",
        "",
        "Intervals use 1000 patient-level bootstrap resamples (seed 42).",
        "",
        "## Per label",
        "",
        "| Label | Positives | AUROC | AUROC 95% CI | AUPRC | AUPRC 95% CI | TP | FP | FN | TN |",
        "|---|---:|---:|---|---:|---|---:|---:|---:|---:|",
    ]
    for label, row in data["per_label"].items():
        c = row["confusion_at_0_5"]
        auroc = "n/a" if row["auroc"] is None else f"{row['auroc']:.3f}"
        auprc = "n/a" if row["auprc"] is None else f"{row['auprc']:.3f}"
        lines.append(
            f"| {label} | {row['positive_count']} | {auroc} | {fmt_ci(row.get('auroc_95ci'))} | "
            f"{auprc} | {fmt_ci(row.get('auprc_95ci'))} | {c['true_positive']} | {c['false_positive']} | "
            f"{c['false_negative']} | {c['true_negative']} |"
        )
    lines += [
        "",
        "Labels with zero positives (for example Hernia in this sample) have no AUROC.",
        "",
        "## Subgroups",
        "",
        "Computed by `tools/subgroup_bias.py` from the per-image predictions. A label is scored in a group",
        "only with at least 5 positives and 5 negatives there, so the subgroup macro figures use slightly",
        "fewer labels than the overall figure above. The macro AUROC for `all` here is therefore not",
        "directly comparable to the overall table.",
        "",
        "| Group | Images | Patients | Labels scored | Macro AUROC | 95% CI (patient bootstrap) | Macro AUPRC | Micro F1 at 0.5 |",
        "|---|---:|---:|---:|---:|---|---:|---:|",
    ]
    subgroups = pd.read_csv(RESULTS / "subgroup_metrics.csv")
    for _, row in subgroups.iterrows():
        ci = row["macro_auroc_95ci_patient_bootstrap"]
        ci_text = "not estimable" if pd.isna(ci) else str(ci).replace("(", "").replace(")", "").replace(", ", "–")
        lines.append(
            f"| {row['group_type']}: {row['group']} | {row['images']} | {row['patients']} | "
            f"{row['labels_evaluated']} | {row['macro_auroc']:.3f} | {ci_text} | "
            f"{row['macro_auprc']:.3f} | {row['micro_f1_at_0_5']:.3f} |"
        )
    return "\n".join(lines) + "\n"


def main() -> None:
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(build(), encoding="utf-8")
    print(f"wrote {OUTPUT}")


if __name__ == "__main__":
    main()
